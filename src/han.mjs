// 解析成 Map（同字对 / 长度不符的条目直接跳过）
const MAP = new Map()
for (const group of GROUPS) {
  for (const pair of group.split(/\s+/)) {
    if (pair.length !== 2) continue
    const [from, to] = pair
    if (from === to) continue
    MAP.set(from, to)
  }
}

export const HAN_TABLE_SIZE = MAP.size

// 繁体 → 简体（逐字折叠）。表外的字原样保留，交给谐音/解码通道兜底。
export function foldHan(text) {
  const src = String(text ?? "")
  let out = ""
  for (const ch of src) out += MAP.get(ch) ?? ch
  return out
}
